def save_model_and_artifacts(
    model,
    tokenizer,
    output_dir: str | Path,
    config: dict[str, Any],
    training_args: TrainingArguments,
    eval_results: dict[str, float] | None = None,
):
    """Save final model and training artifacts."""
    import gc
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    logger.info(f"Saving model and artifacts to {output_dir}")

    # Free up memory before saving
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    # Move model to CPU for saving to avoid GPU memory issues
    model_device = next(model.parameters()).device
    model.cpu()
    gc.collect()
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

    # Save model - use pytorch format to avoid safetensors memory issues
    try:
        model.save_pretrained(output_dir, safe_serialization=False)
    except Exception as e:
        logger.warning(f"Standard save failed: {e}, trying state_dict save")
        torch.save(model.state_dict(), output_dir / "pytorch_model.bin")
        model.config.save_pretrained(output_dir)
    finally:
        # Move model back to original device
        model.to(model_device)

    logger.info("  - Model saved")

    # Save tokenizer
    tokenizer.save_pretrained(output_dir)
    logger.info("  - Tokenizer saved")

    # Save config
    with open(output_dir / "training_config.yaml", "w") as f:
        yaml.dump(config, f, default_flow_style=False)
    logger.info("  - Training config saved")

    # Save training args
    with open(output_dir / "training_args.json", "w") as f:
        json.dump(training_args.to_dict(), f, indent=2)
    logger.info("  - Training args saved")

    # Save eval results
    if eval_results:
        with open(output_dir / "eval_results.json", "w") as f:
            json.dump(eval_results, f, indent=2)
        logger.info("  - Eval results saved")

    # Save completion marker
    with open(output_dir / "training_complete.json", "w") as f:
        json.dump({
            "completed_at": datetime.now().isoformat(),
            "final_eval_loss": eval_results.get("eval_loss") if eval_results else None,
        }, f, indent=2)

    logger.info("Model and artifacts saved successfully!")


