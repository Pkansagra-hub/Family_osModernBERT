_TRAINER_INSTANCE = None
_INTERRUPT_RECEIVED = False


def _signal_handler(signum, frame):
    """Handle interrupt signal - save checkpoint before exit."""
    global _INTERRUPT_RECEIVED
    if _INTERRUPT_RECEIVED:
        logger.warning("Second interrupt received, forcing exit...")
        sys.exit(1)

    _INTERRUPT_RECEIVED = True
    logger.warning("=" * 60)
    logger.warning("INTERRUPT RECEIVED - Saving checkpoint before exit...")
    logger.warning("=" * 60)

    if _TRAINER_INSTANCE is not None:
        try:
            # Save current checkpoint
            _TRAINER_INSTANCE.save_model()
            _TRAINER_INSTANCE.save_state()
            logger.info("Checkpoint saved successfully!")
            logger.info(f"Resume with: --resume_from_checkpoint {_TRAINER_INSTANCE.args.output_dir}")
        except Exception as e:
            logger.error(f"Failed to save checkpoint: {e}")

    sys.exit(0)


# Register signal handlers
signal.signal(signal.SIGINT, _signal_handler)
signal.signal(signal.SIGTERM, _signal_handler)


