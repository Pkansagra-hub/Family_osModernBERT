def load_datasets(
    config: dict[str, Any],
    tokenizer: AutoTokenizer,
    debug: bool = False,
):
    """
    Load counterfactual datasets for training.

    Args:
        config: Configuration dictionary
        tokenizer: Tokenizer for encoding counterfactual text
        debug: If True, use small subset for testing

    Returns:
        Tuple of (train_dataset, eval_dataset)
    """
    from modeling_studio.data.loaders import load_counterfactual_dataset

    data_config = config.get("data", {})
    train_path = data_config.get("train_path", "data/counterfactual/training")
    mode = data_config.get("embeddings_mode", "precomputed")
    max_input_length = data_config.get("max_input_length", 256)
    max_output_length = data_config.get("max_output_length", 256)
    load_to_ram = data_config.get("load_to_ram", False)
    full_sequence = data_config.get("full_sequence", True)  # Default to full sequence

    logger.info(f"Loading counterfactual dataset from {train_path}")
    logger.info(f"  Mode: {mode}")
    logger.info(f"  Full sequence: {full_sequence}")
    logger.info(f"  Max input length: {max_input_length}")
    logger.info(f"  Max output length: {max_output_length}")
    logger.info(f"  Load to RAM: {load_to_ram}")

    # Load train dataset
    train_dataset = load_counterfactual_dataset(
        data_dir=train_path,
        tokenizer=tokenizer,
        mode=mode,
        split="train",
        max_input_length=max_input_length,
        max_output_length=max_output_length,
        load_to_ram=load_to_ram,
        full_sequence=full_sequence,
    )

    # Load validation dataset
    eval_dataset = load_counterfactual_dataset(
        data_dir=train_path,
        tokenizer=tokenizer,
        mode=mode,
        split="val",
        max_input_length=max_input_length,
        max_output_length=max_output_length,
        load_to_ram=load_to_ram,
        full_sequence=full_sequence,
    )

    # Debug mode: use tiny subsets
    if debug:
        logger.info("DEBUG MODE: Using tiny dataset subsets")
        from modeling_studio.data.counterfactual_dataset import CounterfactualSubset
        train_dataset = CounterfactualSubset(train_dataset, list(range(min(100, len(train_dataset)))))
        eval_dataset = CounterfactualSubset(eval_dataset, list(range(min(50, len(eval_dataset)))))

    logger.info(f"Train samples: {len(train_dataset):,}")
    logger.info(f"Eval samples: {len(eval_dataset):,}")

    return train_dataset, eval_dataset


