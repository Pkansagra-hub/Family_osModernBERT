def load_config(config_path: str | Path) -> dict[str, Any]:
    """Load configuration from YAML file."""
    config_path = Path(config_path)
    if not config_path.exists():
        raise FileNotFoundError(f"Config file not found: {config_path}")

    with open(config_path, encoding="utf-8") as f:
        config = yaml.safe_load(f)

    logger.info(f"Loaded config from {config_path}")
    return config


def apply_overrides(config: dict[str, Any], overrides: list[str]) -> dict[str, Any]:
    """Apply command-line overrides to config."""
    for override in overrides:
        if "=" not in override:
            continue
        key, value = override.split("=", 1)
        key = key.lstrip("-")
        keys = key.split(".")

        # Navigate to the right place in config
        current = config
        for k in keys[:-1]:
            if k not in current:
                current[k] = {}
            current = current[k]

        # Parse value type
        try:
            parsed_value = yaml.safe_load(value)
        except Exception:
            parsed_value = value

        current[keys[-1]] = parsed_value
        logger.info(f"Override: {key} = {parsed_value}")

    return config


def find_latest_checkpoint(checkpoint_dir: str | Path) -> str | None:
    """
    Find the latest checkpoint in a directory.

    Useful for auto-resuming after Colab disconnection.

    Args:
        checkpoint_dir: Directory containing checkpoint-XXXX folders

    Returns:
        Path to latest checkpoint, or None if no checkpoints found
    """
    checkpoint_dir = Path(checkpoint_dir)
    if not checkpoint_dir.exists():
        return None

    # Find all checkpoint folders
    checkpoint_pattern = re.compile(r"checkpoint-(\d+)$")
    checkpoints = []

    for folder in checkpoint_dir.iterdir():
        if folder.is_dir():
            match = checkpoint_pattern.match(folder.name)
            if match:
                step = int(match.group(1))
                checkpoints.append((step, folder))

    if not checkpoints:
        return None

    # Return path to latest checkpoint
    latest = max(checkpoints, key=lambda x: x[0])
    return str(latest[1])


