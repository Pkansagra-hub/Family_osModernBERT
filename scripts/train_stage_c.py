def train(
    config: dict[str, Any],
    args: argparse.Namespace,
) -> dict[str, float]:
    """Run the full Stage C training pipeline."""
    global _TRAINER_INSTANCE

    # Set seed
    seed = args.seed if args.seed else config.get("training", {}).get("seed", 42)
    set_seed(seed)
    logger.info(f"Random seed: {seed}")

    # Determine device
    device = "cuda" if torch.cuda.is_available() else "cpu"
    logger.info(f"Device: {device}")

    if device == "cuda":
        logger.info(f"  GPU: {torch.cuda.get_device_name(0)}")
        logger.info(f"  Memory: {torch.cuda.get_device_properties(0).total_memory / 1e9:.1f} GB")

    # Initialize tokenizer
    tokenizer = init_tokenizer(config)

    # Load base model (already on device from load_checkpoint)
    model = load_base_model(config, device=device)

    # Initialize decoder head (pass tokenizer for vocab_size and special tokens)
    model = initialize_decoder_head(model, config, tokenizer=tokenizer)

    # Note: model is already on device from load_base_model, no need to call .to(device) again

    # Freeze encoder and existing heads
    from modeling_studio.trainers.decoder_trainer import freeze_encoder_and_heads
    model_config = config.get("model", {})
    freeze_encoder_and_heads(
        model,
        freeze_encoder=model_config.get("freeze_encoder", True),
        freeze_heads=model_config.get("freeze_existing_heads", True),
        decoder_head_name="counterfactual",
    )

    # Load datasets
    train_dataset, eval_dataset = load_datasets(config, tokenizer, debug=args.debug)

    # Create data collator
    from modeling_studio.trainers.decoder_collator import CounterfactualCollator
    data_collator = CounterfactualCollator(
        tokenizer=tokenizer,
        max_output_length=config.get("data", {}).get("max_output_length", 256),
    )

    # Dry run: validate without training
    if args.dry_run:
        logger.info("Dry run complete - config and data validated successfully")
        return {}

    # Create training arguments
    checkpoint_dir = args.checkpoint_dir or config.get("training", {}).get(
        "checkpoint_dir", "checkpoints/ultrabert-gen-decoder-v1"
    )
    output_dir = args.output_dir or config.get("training", {}).get(
        "output_dir", "outputs/ultrabert-gen-decoder-v1"
    )

    training_args = create_training_args(
        config=config,
        output_dir=checkpoint_dir,
        debug=args.debug,
    )

    # Create trainer
    from modeling_studio.trainers.decoder_trainer import DecoderTrainer, GenerationEvalCallback

    decoder_config = config.get("decoder", {})
    aux_loss_weight = decoder_config.get("load_balancing_loss_weight", 0.01) + \
                      decoder_config.get("router_z_loss_weight", 0.001)

    # Create evaluation callbacks
    callbacks = _create_eval_callbacks(
        config=config,
        tokenizer=tokenizer,
        eval_dataset=eval_dataset,
        debug=args.debug,
    )

    trainer = DecoderTrainer(
        model=model,
        args=training_args,
        train_dataset=train_dataset,
        eval_dataset=eval_dataset,
        data_collator=data_collator,
        tokenizer=tokenizer,
        aux_loss_weight=aux_loss_weight,
        callbacks=callbacks,
    )

    # Store trainer for signal handler
    _TRAINER_INSTANCE = trainer

    # Determine resume checkpoint
    resume_checkpoint = args.resume_from_checkpoint
    if args.auto_resume and resume_checkpoint is None:
        resume_checkpoint = find_latest_checkpoint(checkpoint_dir)
        if resume_checkpoint:
            logger.info(f"Auto-resuming from: {resume_checkpoint}")

    # Log training info
    logger.info("=" * 60)
    logger.info("Starting Stage C Training: Counterfactual MoE Decoder")
    logger.info("=" * 60)
    logger.info(f"Checkpoint directory: {checkpoint_dir}")
    logger.info(f"Output directory: {output_dir}")
    logger.info(f"Train samples: {len(train_dataset):,}")
    logger.info(f"Eval samples: {len(eval_dataset):,}")
    logger.info(f"Effective batch size: {training_args.per_device_train_batch_size * training_args.gradient_accumulation_steps}")
    logger.info(f"Epochs: {training_args.num_train_epochs}")
    logger.info(f"Save every: {training_args.save_steps} steps")
    if resume_checkpoint:
        logger.info(f"Resuming from: {resume_checkpoint}")
    logger.info("=" * 60)
    logger.info("Press Ctrl+C to save checkpoint and exit gracefully")
    logger.info("=" * 60)

    # Train
    train_result = trainer.train(resume_from_checkpoint=resume_checkpoint)

    # Log training results
    logger.info("Training completed!")
    logger.info(f"Training loss: {train_result.training_loss:.4f}")
    logger.info(f"Training steps: {train_result.global_step}")

    # Evaluate
    logger.info("Running final evaluation...")
    eval_results = trainer.evaluate()

    # Log eval results
    logger.info("Final evaluation results:")
    for metric, value in sorted(eval_results.items()):
        if isinstance(value, float):
            logger.info(f"  {metric}: {value:.4f}")

    # Save final model
    save_model_and_artifacts(
        model=model,
        tokenizer=tokenizer,
        output_dir=output_dir,
        config=config,
        training_args=training_args,
        eval_results=eval_results,
    )

    return eval_results


