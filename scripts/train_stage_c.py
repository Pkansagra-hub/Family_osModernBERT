#!/usr/bin/env python
"""
Stage C Training Script: Counterfactual MoE Decoder

This script trains the MoE decoder head for counterfactual generation.
The encoder and existing 12 heads are FROZEN - only the decoder trains.

Design Principles:
    1. Colab-friendly: Designed for 18-hour runtime limits
    2. Resume-robust: Saves frequently, easy to resume from any checkpoint
    3. Memory-efficient: Gradient checkpointing, bf16, optimized batch sizes
    4. Production-ready: Proper logging, metrics, error handling

Training Data:
    - Generated by: scripts/agents/counterfactual_data_generator.py
    - Prepared by: scripts/agents/prepare_decoder_training_data.py
    - Location: data/counterfactual/training/
        - samples.jsonl: Text data
        - embeddings.h5: Precomputed encoder embeddings (768-dim)
        - train_val_split.json: 95/5 split indices

Architecture (~420M trainable params):
    - Encoder: 155M params (FROZEN)
    - Existing 12 heads: ~10M params (FROZEN)
    - Decoder: 8 layers (2 dense + 6 MoE), ~420M params (TRAINABLE)
    - 8 experts per MoE layer, top-2 routing
    - 1 shared expert (always active)

Usage:
    # Standard training
    python scripts/train_stage_c.py --config configs/training/multitask/stage_c_decoder.yaml

    # Resume from checkpoint (critical for Colab)
    python scripts/train_stage_c.py \
        --config configs/training/multitask/stage_c_decoder.yaml \
        --resume_from_checkpoint checkpoints/ultrabert-gen-decoder-v1/checkpoint-5000

    # Debug mode (small batches, fast epochs)
    python scripts/train_stage_c.py \
        --config configs/training/multitask/stage_c_decoder.yaml \
        --debug

    # Find latest checkpoint automatically
    python scripts/train_stage_c.py \
        --config configs/training/multitask/stage_c_decoder.yaml \
        --auto_resume

Environment:
    - GPU: Colab T4/V100 (16GB+), A100 preferred (40GB)
    - RAM: 16GB+ (32GB recommended)
    - Disk: ~5GB for checkpoints

Output:
    - checkpoints/ultrabert-gen-decoder-v1/: Training checkpoints (saved every 500 steps)
    - outputs/ultrabert-gen-decoder-v1/: Final model, configs, eval results
"""

