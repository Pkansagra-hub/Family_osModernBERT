def create_training_args(
    config: dict[str, Any],
    output_dir: str | None = None,
    debug: bool = False,
) -> TrainingArguments:
    """Create training arguments from config."""
    training_config = config.get("training", {})

    # Determine output directory
    if output_dir is None:
        output_dir = training_config.get("checkpoint_dir", "checkpoints/ultrabert-gen-decoder-v1")

    # Check bf16 support
    bf16_supported = torch.cuda.is_available() and torch.cuda.is_bf16_supported()
    bf16_config = training_config.get("bf16", True)
    fp16_config = training_config.get("fp16", False)

    if bf16_config and not bf16_supported:
        logger.warning("bf16 not supported, falling back to fp16")
        bf16_config = False
        fp16_config = True

    # Get batch sizes
    train_batch_size = training_config.get("per_device_train_batch_size", 8)
    eval_batch_size = training_config.get("per_device_eval_batch_size", 16)
    gradient_checkpointing = training_config.get("gradient_checkpointing", True)

    # Dataloader settings
    dataloader_num_workers = training_config.get("num_workers", 4)

    # Debug mode adjustments
    if debug:
        train_batch_size = min(train_batch_size, 4)
        eval_batch_size = min(eval_batch_size, 8)
        gradient_checkpointing = True
        dataloader_num_workers = 0
        training_config["num_train_epochs"] = 1
        training_config["save_steps"] = 50
        training_config["eval_steps"] = 50
        training_config["logging_steps"] = 10
        logger.info(f"Debug: batch_size={train_batch_size}, epochs=1")

    # Build training arguments
    # Note: load_best_model_at_end=True causes double GPU memory usage as Trainer
    # loads checkpoint weights again. Default to False for memory efficiency.
    load_best_model = training_config.get("load_best_model_at_end", False)

    args = TrainingArguments(
        output_dir=output_dir,
        # Optimization
        learning_rate=float(training_config.get("learning_rate", 2e-4)),
        weight_decay=float(training_config.get("weight_decay", 0.01)),
        max_grad_norm=float(training_config.get("max_grad_norm", 1.0)),
        optim=training_config.get("optim", "adamw_torch_fused"),
        # Schedule
        lr_scheduler_type=training_config.get("lr_scheduler_type", "cosine"),
        warmup_ratio=float(training_config.get("warmup_ratio", 0.1)),
        # Training duration
        num_train_epochs=int(training_config.get("num_train_epochs", 10)),
        max_steps=int(training_config.get("max_steps", -1)),
        # Batch sizes
        per_device_train_batch_size=train_batch_size,
        per_device_eval_batch_size=eval_batch_size,
        gradient_accumulation_steps=int(training_config.get("gradient_accumulation_steps", 4)),
        # Mixed precision
        bf16=bf16_config,
        fp16=fp16_config,
        # Memory optimization
        gradient_checkpointing=gradient_checkpointing,
        # Checkpointing (critical for Colab)
        save_strategy=training_config.get("save_strategy", "steps"),
        save_steps=int(training_config.get("save_steps", 500)),
        save_total_limit=int(training_config.get("save_total_limit", 5)),
        save_safetensors=training_config.get("save_safetensors", True),
        # Evaluation
        eval_strategy=training_config.get("eval_strategy", "steps"),
        eval_steps=int(training_config.get("eval_steps", 500)),
        # Logging
        logging_strategy=training_config.get("logging_strategy", "steps"),
        logging_steps=int(training_config.get("logging_steps", 50)),
        logging_first_step=training_config.get("logging_first_step", True),
        # Best model - disabled by default to prevent double GPU memory usage
        load_best_model_at_end=load_best_model,
        metric_for_best_model=training_config.get("metric_for_best_model", "eval_loss"),
        greater_is_better=training_config.get("greater_is_better", False),
        # Reporting
        report_to=training_config.get("report_to", ["tensorboard"]),
        # Seed
        seed=int(training_config.get("seed", 42)),
        # Dataloader
        dataloader_num_workers=dataloader_num_workers,
        dataloader_pin_memory=training_config.get("dataloader_pin_memory", True),
        dataloader_prefetch_factor=2 if dataloader_num_workers > 0 else None,
        # Remove unused columns warning
        remove_unused_columns=False,
    )

    return args


