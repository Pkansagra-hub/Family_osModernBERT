def _create_eval_callbacks(
    config: dict[str, Any],
    tokenizer: AutoTokenizer,
    eval_dataset,
    debug: bool = False,
) -> list:
    """
    Create evaluation callbacks for decoder training.

    Callbacks:
        1. GenerationEvalCallback: Runs counterfactual quality metrics
           (completion rate, format adherence, context fidelity)
        2. PerplexityCallback: Logs perplexity during evaluation

    Args:
        config: Training configuration
        tokenizer: Tokenizer for decoding
        eval_dataset: Evaluation dataset for sampling
        debug: Debug mode (fewer samples)

    Returns:
        List of TrainerCallback instances
    """
    from modeling_studio.trainers.decoder_trainer import GenerationEvalCallback

    callbacks = []
    eval_config = config.get("evaluation", {})

    # Extract eval samples for generation quality evaluation
    eval_samples = _extract_eval_samples(
        eval_dataset=eval_dataset,
        tokenizer=tokenizer,
        num_samples=eval_config.get("num_gen_samples", 50 if not debug else 10),
    )

    if eval_samples:
        # GenerationEvalCallback for counterfactual quality metrics
        gen_callback = GenerationEvalCallback(
            tokenizer=tokenizer,
            eval_samples=eval_samples,
            valence=eval_config.get("valence", "positive"),
            eval_every_n_steps=eval_config.get("gen_eval_steps", 500 if not debug else 50),
            max_new_tokens=eval_config.get("max_new_tokens", 64),
            num_samples=eval_config.get("num_gen_samples", 50 if not debug else 10),
            temperature=eval_config.get("temperature", 0.7),
        )
        callbacks.append(gen_callback)
        logger.info(f"Added GenerationEvalCallback with {len(eval_samples)} samples")
    else:
        logger.warning("No eval samples available for GenerationEvalCallback")

    # Add PerplexityLoggingCallback
    ppl_callback = _create_perplexity_callback(config, debug)
    if ppl_callback:
        callbacks.append(ppl_callback)
        logger.info("Added PerplexityLoggingCallback")

    # Add BLEU/ROUGE/Distinct-N callback if enabled
    if eval_config.get("compute_bleu", False) or eval_config.get("compute_rouge", False) or eval_config.get("compute_distinct_n", False):
        text_metrics_callback = _create_text_metrics_callback(
            config=config,
            tokenizer=tokenizer,
            eval_samples=eval_samples,
            debug=debug,
        )
        if text_metrics_callback:
            callbacks.append(text_metrics_callback)
            logger.info("Added TextMetricsCallback (BLEU/ROUGE/Distinct-N)")

    # Add expert utilization callback for MoE debugging
    if eval_config.get("log_expert_utilization", False):
        expert_callback = _create_expert_utilization_callback(
            config=config,
            debug=debug,
        )
        if expert_callback:
            callbacks.append(expert_callback)
            logger.info("Added ExpertUtilizationCallback")

    return callbacks


def _extract_eval_samples(
    eval_dataset,
    tokenizer: AutoTokenizer,
    num_samples: int = 50,
) -> list[tuple[str, str]]:
    """
    Extract (input_text, reference_text) pairs from eval dataset.

    Args:
        eval_dataset: Evaluation dataset (CounterfactualDataset)
        tokenizer: Tokenizer for decoding
        num_samples: Number of samples to extract

    Returns:
        List of (input_text, reference_text) tuples
    """
    samples_list = []
    num_samples = min(num_samples, len(eval_dataset))

    # CounterfactualDataset stores raw samples with text in .samples attribute
    # The __getitem__ only returns tensors, so we need to access .samples directly
    raw_samples = getattr(eval_dataset, "samples", None)
    indices = getattr(eval_dataset, "indices", None)

    if raw_samples is not None and indices is not None:
        # Direct access to raw samples (preferred for CounterfactualDataset)
        for i in range(num_samples):
            try:
                sample_idx = indices[i]
                sample = raw_samples[sample_idx]

                input_text = sample.get("input_text") or sample.get("context") or sample.get("source")
                reference_text = (
                    sample.get("counterfactual_full_text")
                    or sample.get("counterfactual")
                    or sample.get("output_text")
                    or sample.get("target")
                )

                if input_text and reference_text:
                    samples_list.append((input_text, reference_text))

            except Exception as e:
                logger.debug(f"Failed to extract sample {i} from raw samples: {e}")
                continue
    else:
        # Fallback: Try to extract from __getitem__ output
        for i in range(num_samples):
            try:
                item = eval_dataset[i]

                input_text = None
                reference_text = None

                # Try common key names for input
                for key in ["input_text", "input", "context", "source"]:
                    if key in item and isinstance(item[key], str):
                        input_text = item[key]
                        break

                # Try common key names for reference
                for key in ["output_text", "output", "target", "counterfactual", "counterfactual_full_text", "reference"]:
                    if key in item and isinstance(item[key], str):
                        reference_text = item[key]
                        break

                # If text not directly available, decode from token IDs
                if input_text is None and "decoder_input_ids" in item:
                    # For counterfactual dataset, input is encoder embeddings
                    # We can't easily recover text, skip
                    pass

                if reference_text is None and "labels" in item:
                    labels = item["labels"]
                    if hasattr(labels, "tolist"):
                        labels = labels.tolist()
                    # Filter out -100 padding
                    valid_labels = [l for l in labels if l != -100]
                    if valid_labels:
                        reference_text = tokenizer.decode(valid_labels, skip_special_tokens=True)

                # For input_text, try decoding decoder_input_ids as a proxy
                if input_text is None and reference_text is not None and "decoder_input_ids" in item:
                    # Use reference as both (won't compute meaningful BLEU but at least callback runs)
                    input_text = reference_text[:100]  # Truncate as pseudo-input

                if input_text and reference_text:
                    samples_list.append((input_text, reference_text))

            except Exception as e:
                logger.debug(f"Failed to extract sample {i}: {e}")
                continue

    logger.info(f"Extracted {len(samples_list)} eval samples for generation quality")
    return samples_list


def _create_perplexity_callback(config: dict[str, Any], debug: bool = False):
    """
    Create a callback that logs perplexity metrics during evaluation.

    Returns:
        PerplexityLoggingCallback or None if creation fails
    """
    from transformers import TrainerCallback, TrainerControl, TrainerState, TrainingArguments

    class PerplexityLoggingCallback(TrainerCallback):
        """Callback to compute and log perplexity during evaluation."""

        def on_evaluate(
            self,
            args: TrainingArguments,
            state: TrainerState,
            control: TrainerControl,
            metrics: dict[str, float] | None = None,
            **kwargs,
        ) -> TrainerControl:
            """Log perplexity from eval_loss."""
            if metrics and "eval_loss" in metrics:
                import math
                eval_loss = metrics["eval_loss"]
                perplexity = math.exp(eval_loss) if eval_loss < 100 else float("inf")
                logger.info(f"[Perplexity] Step {state.global_step}: {perplexity:.4f}")

                # Log to wandb if available
                if state.is_world_process_zero:
                    try:
                        import wandb
                        if wandb.run is not None:
                            wandb.log({
                                "eval/perplexity": perplexity,
                                "eval/step": state.global_step,
                            })
                    except ImportError:
                        pass

            return control

    return PerplexityLoggingCallback()


def _create_text_metrics_callback(
    config: dict[str, Any],
    tokenizer: AutoTokenizer,
    eval_samples: list[tuple[str, str]],
    debug: bool = False,
):
    """
    Create callback for BLEU, ROUGE, and Distinct-N metrics.

    These metrics are computed on generated text vs references during evaluation.
    """
    from transformers import TrainerCallback, TrainerControl, TrainerState, TrainingArguments

    eval_config = config.get("evaluation", {})
    compute_bleu = eval_config.get("compute_bleu", True)
    compute_rouge = eval_config.get("compute_rouge", True)
    compute_distinct = eval_config.get("compute_distinct_n", True)

    class TextMetricsCallback(TrainerCallback):
        """Callback to compute BLEU, ROUGE, Distinct-N on generated text."""

        def __init__(self):
            self.eval_samples = eval_samples
            self.tokenizer = tokenizer
            self._last_eval_step = -1

        def on_evaluate(
            self,
            args: TrainingArguments,
            state: TrainerState,
            control: TrainerControl,
            model=None,
            **kwargs,
        ) -> TrainerControl:
            """Compute text metrics during evaluation."""
            if model is None or not self.eval_samples:
                return control

            # Avoid duplicate computation
            if state.global_step == self._last_eval_step:
                return control
            self._last_eval_step = state.global_step

            try:
                predictions, references = self._generate_predictions(model, state)

                if not predictions:
                    return control

                metrics = {}

                # BLEU
                if compute_bleu:
                    try:
                        from modeling_studio.evaluation.decoder_metrics import compute_bleu as calc_bleu
                        bleu = calc_bleu(predictions, references)
                        metrics["text_metrics/bleu"] = bleu
                        logger.info(f"[TextMetrics] BLEU: {bleu:.2f}")
                    except Exception as e:
                        logger.warning(f"BLEU computation failed: {e}")

                # ROUGE
                if compute_rouge:
                    try:
                        from modeling_studio.evaluation.decoder_metrics import compute_rouge as calc_rouge
                        rouge = calc_rouge(predictions, references)
                        for key, value in rouge.items():
                            metrics[f"text_metrics/{key}"] = value
                        logger.info(f"[TextMetrics] ROUGE-L: {rouge.get('rougeL', 0):.4f}")
                    except Exception as e:
                        logger.warning(f"ROUGE computation failed: {e}")

                # Distinct-N
                if compute_distinct:
                    try:
                        from modeling_studio.evaluation.decoder_metrics import compute_distinct_n
                        distinct = compute_distinct_n(predictions)
                        for key, value in distinct.items():
                            metrics[f"text_metrics/{key}"] = value
                        logger.info(f"[TextMetrics] Distinct-2: {distinct.get('distinct-2', 0):.4f}")
                    except Exception as e:
                        logger.warning(f"Distinct-N computation failed: {e}")

                # Log to wandb
                if metrics and state.is_world_process_zero:
                    try:
                        import wandb
                        if wandb.run is not None:
                            metrics["text_metrics/step"] = state.global_step
                            wandb.log(metrics)
                    except ImportError:
                        pass

            except Exception as e:
                logger.warning(f"TextMetricsCallback error: {e}")

            return control

        def _generate_predictions(self, model, state) -> tuple[list[str], list[str]]:
            """Generate predictions for eval samples."""
            import torch

            model.eval()
            device = next(model.parameters()).device
            predictions = []
            references = []

            # Get decoder head
            if hasattr(model, "heads") and "counterfactual" in model.heads:
                decoder_head = model.heads["counterfactual"]
            elif hasattr(model, "decoder"):
                decoder_head = model.decoder
            else:
                decoder_head = model

            num_samples = min(20 if not debug else 5, len(self.eval_samples))

            with torch.no_grad():
                for input_text, ref_text in self.eval_samples[:num_samples]:
                    try:
                        encoded = self.tokenizer(
                            input_text,
                            return_tensors="pt",
                            truncation=True,
                            max_length=256,
                            padding=True,
                        )
                        input_ids = encoded["input_ids"].to(device)

                        if hasattr(decoder_head, "generate"):
                            output_ids = decoder_head.generate(
                                input_ids=input_ids,
                                max_new_tokens=64,
                                temperature=0.7,
                                do_sample=True,
                            )
                            pred_text = self.tokenizer.decode(
                                output_ids[0], skip_special_tokens=True
                            )
                            predictions.append(pred_text)
                            references.append(ref_text)
                    except Exception as e:
                        logger.debug(f"Generation failed: {e}")
                        continue

            model.train()
            return predictions, references

    return TextMetricsCallback()


def _create_expert_utilization_callback(
    config: dict[str, Any],
    debug: bool = False,
):
    """
    Create callback for logging MoE expert utilization stats.

    Tracks load balancing across experts to detect expert collapse.
    """
    from transformers import TrainerCallback, TrainerControl, TrainerState, TrainingArguments

    eval_config = config.get("evaluation", {})
    log_steps = eval_config.get("expert_util_steps", 1000 if not debug else 100)

    class ExpertUtilizationCallback(TrainerCallback):
        """Callback to log MoE expert utilization statistics."""

        def __init__(self):
            self._last_log_step = 0

        def on_step_end(
            self,
            args: TrainingArguments,
            state: TrainerState,
            control: TrainerControl,
            model=None,
            **kwargs,
        ) -> TrainerControl:
            """Log expert utilization stats periodically."""
            if model is None:
                return control

            steps_since_log = state.global_step - self._last_log_step
            if steps_since_log < log_steps:
                return control

            self._last_log_step = state.global_step

            try:
                # Get decoder head
                if hasattr(model, "heads") and "counterfactual" in model.heads:
                    decoder_head = model.heads["counterfactual"]
                elif hasattr(model, "decoder"):
                    decoder_head = model.decoder
                else:
                    return control

                # Check if MoE decoder with expert tracking
                if not hasattr(decoder_head, "get_expert_utilization"):
                    return control

                util_stats = decoder_head.get_expert_utilization()

                if util_stats:
                    logger.info(f"[ExpertUtil] Step {state.global_step}:")
                    for layer_idx, stats in util_stats.items():
                        avg_util = sum(stats.values()) / len(stats) if stats else 0
                        min_util = min(stats.values()) if stats else 0
                        max_util = max(stats.values()) if stats else 0
                        logger.info(f"  Layer {layer_idx}: avg={avg_util:.3f}, min={min_util:.3f}, max={max_util:.3f}")

                    # Log to wandb
                    if state.is_world_process_zero:
                        try:
                            import wandb
                            if wandb.run is not None:
                                wandb_metrics = {"expert_util/step": state.global_step}
                                for layer_idx, stats in util_stats.items():
                                    for expert_id, util in stats.items():
                                        wandb_metrics[f"expert_util/layer{layer_idx}_expert{expert_id}"] = util
                                wandb.log(wandb_metrics)
                        except ImportError:
                            pass

            except Exception as e:
                logger.debug(f"Expert utilization logging failed: {e}")

            return control

    return ExpertUtilizationCallback()


